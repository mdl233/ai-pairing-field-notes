/** 列出全部工作流（只给名字与用途，轻量） */
export function listWorkflows() {
  return WORKFLOWS.map((w) => ({ name: w.name, when: w.when, steps: w.steps.length }));
}

/** 取一个工作流；支持模糊匹配（"发布" → "发布 / 交付前检查"） */
export function getWorkflow(name) {
  const q = String(name || '').trim();
  if (!q) return undefined;
  const norm = (s) => s.replace(/[\s/·、，]/g, '');
  const nq = norm(q);
  return (
    WORKFLOWS.find((w) => w.name === q) ||
    WORKFLOWS.find((w) => norm(w.name) === nq) ||
    WORKFLOWS.find((w) => norm(w.name).includes(nq)) ||
    WORKFLOWS.find((w) => nq.includes(norm(w.name))) ||
    WORKFLOWS.find((w) => w.name.includes(q))
  );
}
